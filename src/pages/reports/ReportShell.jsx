import { Link } from 'react-router-dom';
import { ArrowLeft, Printer } from 'lucide-react';
import { Button, Notice } from '../../components/ui.jsx';
import { api } from '../../lib/api.js';
import { dateTime } from '../../lib/format.js';
import { useAuth } from '../../lib/auth.jsx';
import { useLoad } from '../../lib/useLoad.js';

// Common frame for every report: back link, filters, print button, and a
// printable header with the cooperative's logo, name, and address.
export default function ReportShell({ report, title, subtitle, generatedAt, filters, printBody, back = '/reports', personal = true, children }) {
  const { user } = useAuth();
  const coop = useLoad('/cooperative');
  const canPrint = user.features.includes('pdf_reports');
  const c = coop.data?.cooperative;

  const onPrint = async () => {
    try {
      await api('/reports/printed', { method: 'POST', body: { report, ...printBody } });
      window.print();
    } catch (err) {
      alert(err.message); // eslint-disable-line no-alert
    }
  };

  return (
    <div>
      <div className="mb-4 flex flex-wrap items-center justify-between gap-3 print:hidden">
        <Link to={back} className="inline-flex items-center gap-1 text-sm text-muted hover:text-ink"><ArrowLeft size={16} /> {back === '/reports' ? 'All reports' : 'Back'}</Link>
        {canPrint
          ? <Button onClick={onPrint} disabled={!generatedAt}><Printer size={16} /> Print or Save as PDF</Button>
          : <p className="text-xs text-muted">Printing reports is not on your plan.</p>}
      </div>
      {filters && <div className="mb-4 print:hidden">{filters}</div>}

      <article className="space-y-5 rounded-xl bg-white p-5 shadow-sm print:space-y-4 print:rounded-none print:p-0 print:shadow-none">
        <header className="flex flex-wrap items-start justify-between gap-4 border-b-2 border-ink pb-4">
          <div className="flex items-center gap-3">
            <img src="/logo.png" alt="" className="h-12 w-12" />
            <div>
              <p className="text-lg font-semibold leading-tight">{c?.facilityName || user.facilityName || user.cooperativeName}</p>
              {c?.address && <p className="text-xs text-muted">{c.address}</p>}
            </div>
          </div>
          <div className="text-right">
            <h1 className="text-xl leading-tight">{title}</h1>
            {subtitle && <p className="text-sm text-muted">{subtitle}</p>}
            {generatedAt && <p className="text-xs text-muted">As of {dateTime(generatedAt)}</p>}
          </div>
        </header>
        {children}
        <p className="pt-2 text-center text-[11px] text-muted">Generated by OnioNet{user.name ? ` for ${user.name}` : ''}.{personal && ' Contains personal data; handle under the Data Privacy Act.'}</p>
      </article>
    </div>
  );
}

export function Loading({ error }) {
  return error ? <Notice>{error}</Notice> : <p className="text-sm text-muted">Loading…</p>;
}

export function Section({ title, children }) {
  return (
    <section className="break-inside-auto">
      <h2 className="mb-2 text-base">{title}</h2>
      {children}
    </section>
  );
}

// A row of summary figures at the top of a report.
export function Figures({ items }) {
  return (
    <dl className={`grid grid-cols-2 gap-3 ${items.length > 4 ? 'sm:grid-cols-5 print:grid-cols-5' : 'sm:grid-cols-4 print:grid-cols-4'}`}>
      {items.map(([label, value, tone]) => (
        <div key={label} className="rounded-lg bg-page p-3 print:border print:border-line print:bg-white">
          <dt className="text-xs text-muted">{label}</dt>
          <dd className={`text-lg font-bold ${tone ?? ''}`}>{value}</dd>
        </div>
      ))}
    </dl>
  );
}

// From/To date filter for reports over a period.
export function DateRange({ from, to, onChange }) {
  const input = 'mt-1 rounded-lg border border-line bg-white px-3 py-2 text-sm';
  return (
    <div className="flex flex-wrap items-end gap-3 rounded-xl bg-white p-4 shadow-sm">
      <label className="text-xs text-muted">From<input type="date" value={from} max={to} onChange={(e) => onChange({ from: e.target.value, to })} className={`${input} block`} /></label>
      <label className="text-xs text-muted">To<input type="date" value={to} min={from} onChange={(e) => onChange({ from, to: e.target.value })} className={`${input} block`} /></label>
    </div>
  );
}

export const defaultRange = () => {
  const d = (x) => `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, '0')}-${String(x.getDate()).padStart(2, '0')}`;
  const now = new Date();
  return { from: d(new Date(now.getTime() - 29 * 86_400_000)), to: d(now) };
};
