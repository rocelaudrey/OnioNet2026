import { Link, useParams } from 'react-router-dom';
import { ArrowLeft, Printer } from 'lucide-react';
import { Button, Notice } from '../../components/ui.jsx';
import { date, dateTime, number } from '../../lib/format.js';
import { useLoad } from '../../lib/useLoad.js';

function Line({ label, children }) {
  return (
    <div className="flex justify-between gap-4 border-b border-line py-1.5 text-sm">
      <dt className="text-muted">{label}</dt>
      <dd className="text-right font-medium">{children}</dd>
    </div>
  );
}

// Printed in the browser (the print dialog can also save a PDF).
export default function ReleaseSlip() {
  const { releaseNo } = useParams();
  const { data, error, loading } = useLoad(`/custody/releases/${releaseNo}`);

  if (loading) return <p className="text-sm text-muted">Loading…</p>;
  if (error) return <Notice>{error}</Notice>;
  const { slip } = data;

  return (
    <div className="mx-auto max-w-2xl">
      <div className="mb-4 flex flex-wrap items-center justify-between gap-3 print:hidden">
        <Link to={`/inventory/${slip.batchId}`} className="inline-flex items-center gap-1 text-sm text-muted hover:text-ink">
          <ArrowLeft size={16} /> Delivery details
        </Link>
        <Button onClick={() => window.print()}><Printer size={16} /> Print or Save as PDF</Button>
      </div>

      <article className="rounded-xl bg-white p-6 shadow-sm print:rounded-none print:p-0 print:shadow-none">
        <header className="flex items-start justify-between gap-4 border-b-2 border-ink pb-4">
          <div className="flex items-center gap-3">
            <img src="/logo.png" alt="" className="h-12 w-12" />
            <div>
              <p className="text-lg font-semibold leading-tight">{slip.cooperative.facilityName || slip.cooperative.name}</p>
              <p className="text-xs text-muted">{slip.cooperative.address}</p>
            </div>
          </div>
          <div className="text-right">
            <p className="text-lg font-semibold leading-tight">Release Slip</p>
            <p className="font-mono text-sm">{slip.releaseNo}</p>
          </div>
        </header>

        <dl className="mt-4 grid gap-x-8 sm:grid-cols-2 print:grid-cols-2">
          <div>
            <Line label="Released to">{slip.ownerName}</Line>
            {slip.memberNo && <Line label="Member No.">{slip.memberNo}</Line>}
            <Line label="Delivery No.">{slip.batchNo}</Line>
            {slip.variety && <Line label="Variety">{slip.variety}</Line>}
          </div>
          <div>
            <Line label="Date">{date(slip.finishedAt)}</Line>
            <Line label="Released by">{slip.staff.join(', ')}</Line>
            <Line label="Sacks released">{number(slip.sacksReleased)}</Line>
            <Line label="Sacks remaining in storage">{number(slip.sacksRemaining)}</Line>
          </div>
        </dl>

        <h2 className="mb-2 mt-6 text-sm">Sacks released ({number(slip.sacksReleased)})</h2>
        <table className="w-full text-left text-sm">
          <thead>
            <tr className="border-b border-ink text-xs text-muted">
              <th className="py-1.5 font-normal">Sack</th>
              <th className="py-1.5 font-normal">Tag</th>
              <th className="py-1.5 font-normal">Stored in</th>
              <th className="py-1.5 text-right font-normal">Released at</th>
            </tr>
          </thead>
          <tbody>
            {slip.sacks.map((s) => (
              <tr key={s.sackNo} className="border-b border-line">
                <td className="py-1.5">Sack {s.sackNo}</td>
                <td className="py-1.5 font-mono text-xs">{s.tagCode}</td>
                <td className="py-1.5">{s.quadrantCode}</td>
                <td className="py-1.5 text-right">{dateTime(s.releasedAt)}</td>
              </tr>
            ))}
          </tbody>
        </table>

        <div className="mt-12 grid grid-cols-2 gap-10 text-center text-xs text-muted">
          <div><div className="border-t border-ink pt-1">Released by (name and signature)</div></div>
          <div><div className="border-t border-ink pt-1">Received by (name and signature)</div></div>
        </div>
        <p className="mt-6 text-center text-[11px] text-muted">The tags on these sacks were scanned out and returned to the cooperative. Generated by OnioNet.</p>
      </article>
    </div>
  );
}
