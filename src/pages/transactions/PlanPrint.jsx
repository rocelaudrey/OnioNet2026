import { Link, useParams } from 'react-router-dom';
import { ArrowLeft, Printer } from 'lucide-react';
import { Button, Notice } from '../../components/ui.jsx';
import { date, dateTime, formatPHP } from '../../lib/format.js';
import { useAuth } from '../../lib/auth.jsx';
import { useLoad } from '../../lib/useLoad.js';
import { Schedule } from './PlanCard.jsx';
import { FREQUENCY_LABELS } from './labels.jsx';

// Printable installment schedule, signed by the farmer and the cooperative.
export default function PlanPrint() {
  const { id } = useParams();
  const { user } = useAuth();
  const { data, error, loading } = useLoad(`/batches/${id}`);
  if (loading) return <p className="text-sm text-muted">Loading…</p>;
  if (error) return <Notice>{error}</Notice>;
  const { batch, account } = data;
  const { plan } = account;
  if (!plan) return <Notice>This delivery has no installment plan.</Notice>;

  return (
    <div className="mx-auto max-w-2xl">
      <div className="mb-4 flex flex-wrap items-center justify-between gap-3 print:hidden">
        <Link to={`/inventory/${id}`} className="inline-flex items-center gap-1 text-sm text-muted hover:text-ink"><ArrowLeft size={16} /> Delivery details</Link>
        <Button onClick={() => window.print()}><Printer size={16} /> Print or Save as PDF</Button>
      </div>
      <article className="rounded-xl bg-white p-6 shadow-sm print:rounded-none print:p-0 print:shadow-none">
        <header className="flex items-start justify-between gap-4 border-b-2 border-ink pb-4">
          <div className="flex items-center gap-3">
            <img src="/logo.png" alt="" className="h-12 w-12" />
            <p className="text-lg font-semibold leading-tight">{user.facilityName || user.cooperativeName}</p>
          </div>
          <div className="text-right">
            <p className="text-lg font-semibold leading-tight">Installment Plan</p>
            <p className="font-mono text-sm">{batch.batchNo}</p>
          </div>
        </header>
        <dl className="mt-4 grid gap-x-8 text-sm sm:grid-cols-2 print:grid-cols-2">
          {[
            ['Farmer', batch.ownerName],
            ['Delivery No.', batch.batchNo],
            ['Plan total', formatPHP(plan.totalCentavos)],
            ['Payments', `${plan.installments.length}, ${FREQUENCY_LABELS[plan.frequency].toLowerCase()}`],
            ['Set up', `${date(plan.createdAt)} by ${plan.createdByName}`],
            ['Paid so far', formatPHP(plan.paidCentavos)],
          ].map(([label, value]) => (
            <div key={label} className="flex justify-between gap-4 border-b border-line py-1.5"><dt className="text-muted">{label}</dt><dd className="text-right font-medium">{value}</dd></div>
          ))}
        </dl>
        <div className="mt-6"><Schedule installments={plan.installments} /></div>
        <p className="mt-4 text-xs text-muted">
          Payments of any amount may be made at any time and are applied to the earliest unpaid installment. Overdue storage fees that build up after {date(plan.createdAt)} are not part of this plan.
          {plan.notes && ` Note: ${plan.notes}`}
        </p>
        <div className="mt-12 grid grid-cols-2 gap-10 text-center text-xs text-muted">
          <div><div className="border-t border-ink pt-1">For the cooperative (name and signature)</div></div>
          <div><div className="border-t border-ink pt-1">Farmer (name and signature)</div></div>
        </div>
        <p className="mt-6 text-center text-[11px] text-muted">Printed {dateTime(new Date())}. Generated by OnioNet.</p>
      </article>
    </div>
  );
}
